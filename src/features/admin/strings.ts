/** Resolve an error key (from fieldErrors or a result status) to Japanese. */
export function errorText(key: string | undefined): string {
  if (!key) return S.errors.generic as string
  const v = S.errors[key]
  return typeof v === 'string' ? v : (S.errors.invalid as string)
}

/** First message of an `invalid` result, for a toast. */
export function firstFieldError(fieldErrors: Record<string, string[]>): string {
  const first = Object.values(fieldErrors)[0]?.[0]
  return errorText(first)
}
