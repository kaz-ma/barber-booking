"""
Build the access-map geometry (src/app/(public)/_components/access-map-geometry.ts) from an
OpenStreetMap extract. Run by hand when the map needs refreshing; the output is committed.

  curl -A "<contact>" -o /tmp/osm.xml \
    "https://api.openstreetmap.org/api/0.6/map?bbox=135.5085,34.6405,135.5160,34.6475"
  python3 scripts/access-map/build.py /tmp/osm.xml

Map data © OpenStreetMap contributors (ODbL). The page shows the attribution.
Shop point: GSI address search for 阿倍野筋二丁目4番48号, snapped to the OSM building with
addr:block_number=4 / addr:housenumber=48.
"""
import math
import sys
import xml.etree.ElementTree as ET

SRC = sys.argv[1]
OUT = 'src/app/(public)/_components/access-map-geometry.ts'

# Bounding box (south, west, north, east) and output width in SVG units.
S, W, N, E = 34.6417, 135.5100, 34.6480, 135.5160
WIDTH = 360.0
KX = math.cos(math.radians((S + N) / 2))
HEIGHT = round(WIDTH * (N - S) / ((E - W) * KX), 1)


def xy(lat, lon):
    return (round((lon - W) / (E - W) * WIDTH, 1), round((N - lat) / (N - S) * HEIGHT, 1))


root = ET.parse(SRC).getroot()
nodes = {n.get('id'): (float(n.get('lat')), float(n.get('lon'))) for n in root.findall('node')}
ways = []
for w in root.findall('way'):
    tags = {t.get('k'): t.get('v') for t in w.findall('tag')}
    pts = [nodes[nd.get('ref')] for nd in w.findall('nd') if nd.get('ref') in nodes]
    ways.append((w.get('id'), tags, pts))


def inside(pts, pad=0.0008):
    return any(S - pad < la < N + pad and W - pad < lo < E + pad for la, lo in pts)


def path(pts, close=False):
    out = []
    last = None
    for i, (la, lo) in enumerate(pts):
        p = xy(la, lo)
        if p == last:
            continue
        out.append(('M' if i == 0 else 'L') + f'{p[0]:g} {p[1]:g}')
        last = p
    return ''.join(out) + ('Z' if close else '')


major, minor, rail, tram, bridge, blocks = [], [], [], [], [], {}
for wid, tags, pts in ways:
    if not inside(pts):
        continue
    hw, rw = tags.get('highway'), tags.get('railway')
    underground = tags.get('tunnel') == 'yes' or tags.get('layer', '0').startswith('-')
    if hw in ('primary', 'trunk', 'secondary') and not underground:
        major.append(path(pts))
    elif hw in ('tertiary', 'residential', 'unclassified', 'living_street', 'pedestrian') and not underground:
        minor.append(path(pts))
    elif hw == 'footway' and tags.get('name') == '阿倍野歩道橋':
        bridge.append(path(pts))
    elif rw == 'rail' and not underground:
        rail.append(path(pts))
    elif rw == 'tram':
        tram.append(path(pts))

# Landmark footprints (OSM way ids) -> key used by the component for labels / styling.
LANDMARKS = {
    'harukas': ('name', 'あべのハルカス'),
    'qsmall': ('name', 'あべのキューズタウン'),
    'shop': ('id', '255793058'),
}
for key, (field, value) in LANDMARKS.items():
    for wid, tags, pts in ways:
        if (field == 'id' and wid == value) or (field == 'name' and tags.get('name') == value and 'building' in tags):
            blocks[key] = path(pts, close=True)
stations = [path(pts, close=True) for wid, tags, pts in ways if tags.get('building') == 'train_station' and inside(pts, 0)]

POINTS = {
    'shop': (34.643747, 135.512554),
    'jrGate': (34.6472428, 135.5141288),  # JR 天王寺 中央口改札
    'kintetsu': (34.6454112, 135.5154211),  # 近鉄 大阪阿部野橋
    'abenoMetro': (34.6424856, 135.5119918),  # Osaka Metro 谷町線 阿倍野
    'abenoTram': (34.6421585, 135.5118535),  # 阪堺 阿倍野
    'tramTennoji': (34.64587, 135.51279),  # 阪堺 天王寺駅前
    'tokiwa': (34.64408, 135.51262),  # あべの筋 × 常盤通 crossing
    'harukas': (34.64583, 135.51417),
    'qsmall': (34.64483, 135.51164),
    'footbridge': (34.64655, 135.51270),
}
points = {k: xy(*v) for k, v in POINTS.items()}

# Walking route: JR 中央口 → 阿倍野歩道橋 → east sidewalk of あべの筋 → shop.
ROUTE = [
    (34.6472428, 135.5141288),
    (34.64660, 135.51405),
    (34.64632, 135.51318),
    (34.64600, 135.51300),
    (34.64420, 135.51272),
    (34.64386, 135.51268),
    (34.643747, 135.512554),
]


def ts_list(name, items):
    body = ',\n'.join(f"  '{p}'" for p in items if p)
    return f'export const {name} = [\n{body},\n] as const\n'


with open(OUT, 'w') as f:
    f.write('// Generated by scripts/access-map/build.py from OpenStreetMap data. Do not edit by hand.\n')
    f.write('// Map data © OpenStreetMap contributors (ODbL).\n\n')
    f.write(f'export const MAP_SIZE = {{ width: {WIDTH:g}, height: {HEIGHT:g} }} as const\n\n')
    f.write(ts_list('MAJOR_ROADS', major) + '\n')
    f.write(ts_list('MINOR_ROADS', minor) + '\n')
    f.write(ts_list('RAILWAYS', rail) + '\n')
    f.write(ts_list('TRAMWAY', tram) + '\n')
    f.write(ts_list('FOOTBRIDGE', bridge) + '\n')
    f.write(ts_list('STATION_BUILDINGS', stations) + '\n')
    f.write('export const BLOCKS = {\n' + ''.join(f"  {k}: '{v}',\n" for k, v in blocks.items()) + '} as const\n\n')
    f.write('export const POINTS = {\n' + ''.join(f'  {k}: {{ x: {p[0]:g}, y: {p[1]:g} }},\n' for k, p in points.items()) + '} as const\n\n')
    f.write(f"export const ROUTE = '{path(ROUTE)}'\n")
print('wrote', OUT, 'size', WIDTH, HEIGHT)
