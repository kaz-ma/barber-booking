#!/usr/bin/env bash
# Local PostgreSQL cluster for development and tests (no Docker needed).
#
#   scripts/db-local.sh start   initdb (first run) + start + create barber_dev / barber_test
#   scripts/db-local.sh stop    stop the cluster
#   scripts/db-local.sh status  show status and connection URLs
#   scripts/db-local.sh reset   drop + recreate both databases (cluster keeps running)
#   scripts/db-local.sh url     print DATABASE_URL (dev) — `url test` prints the test URL
#
# Data lives in .local/pg (gitignored). Auth is `trust` on 127.0.0.1 only: dev use only.
# Env overrides: PG_BIN (dir with initdb/pg_ctl/psql), PG_LOCAL_PORT (default 54329),
# PG_LOCAL_OS_USER (OS user that owns the cluster when running as root; default postgres).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BASE="$ROOT/.local/pg"
DATA="$BASE/data"
SOCK="$BASE/run"
LOG="$BASE/postgres.log"
PORT_FILE="$BASE/port"
DEV_DB=barber_dev
TEST_DB=barber_test

find_pg_bin() {
  if [[ -n "${PG_BIN:-}" ]]; then echo "$PG_BIN"; return; fi
  if command -v pg_ctl >/dev/null 2>&1; then dirname "$(command -v pg_ctl)"; return; fi
  for v in 17 16 15; do
    for d in "/usr/lib/postgresql/$v/bin" "/opt/homebrew/opt/postgresql@$v/bin" "/usr/local/opt/postgresql@$v/bin"; do
      if [[ -x "$d/pg_ctl" ]]; then echo "$d"; return; fi
    done
  done
  echo "error: PostgreSQL server binaries not found (set PG_BIN)" >&2
  exit 1
}
BIN="$(find_pg_bin)"

# initdb/postgres refuse to run as root: delegate to an unprivileged OS user.
as_owner() {
  if [[ "$(id -u)" == "0" ]]; then
    runuser -u "${PG_LOCAL_OS_USER:-postgres}" -- "$@"
  else
    "$@"
  fi
}

port_in_use() {
  (echo >"/dev/tcp/127.0.0.1/$1") >/dev/null 2>&1
}

current_port() {
  if [[ -f "$PORT_FILE" ]]; then cat "$PORT_FILE"; else echo "${PG_LOCAL_PORT:-54329}"; fi
}

is_running() {
  [[ -f "$DATA/postmaster.pid" ]] && as_owner "$BIN/pg_ctl" -D "$DATA" status >/dev/null 2>&1
}

url_for() { echo "postgresql://postgres@127.0.0.1:$(current_port)/$1"; }

psql_admin() {
  "$BIN/psql" -h 127.0.0.1 -p "$(current_port)" -U postgres -d postgres -v ON_ERROR_STOP=1 -qtA "$@"
}

ensure_db() {
  local db="$1"
  if [[ "$(psql_admin -c "SELECT 1 FROM pg_database WHERE datname = '$db'")" != "1" ]]; then
    psql_admin -c "CREATE DATABASE $db"
    echo "created database $db"
  fi
}

cmd_start() {
  mkdir -p "$BASE" "$SOCK"
  if [[ "$(id -u)" == "0" ]]; then chown -R "${PG_LOCAL_OS_USER:-postgres}" "$BASE"; fi

  if [[ ! -f "$DATA/PG_VERSION" ]]; then
    echo "initializing cluster in $DATA"
    as_owner "$BIN/initdb" -D "$DATA" -U postgres --auth=trust --encoding=UTF8 --locale=C.UTF-8 >/dev/null
  fi

  if is_running; then
    echo "already running on port $(current_port)"
  else
    local port="${PG_LOCAL_PORT:-54329}"
    [[ -f "$PORT_FILE" ]] && port="$(cat "$PORT_FILE")"
    while port_in_use "$port"; do port=$((port + 1)); done
    echo "$port" >"$PORT_FILE"
    as_owner "$BIN/pg_ctl" -D "$DATA" -l "$LOG" -w \
      -o "-p $port -k $SOCK -c listen_addresses=127.0.0.1 -c TimeZone=UTC -c fsync=off" start >/dev/null
    echo "started on port $port (log: $LOG)"
  fi

  ensure_db "$DEV_DB"
  ensure_db "$TEST_DB"
  print_urls
}

cmd_stop() {
  if is_running; then
    as_owner "$BIN/pg_ctl" -D "$DATA" -m fast -w stop >/dev/null
    echo "stopped"
  else
    echo "not running"
  fi
}

cmd_reset() {
  is_running || cmd_start >/dev/null
  for db in "$DEV_DB" "$TEST_DB"; do
    psql_admin -c "DROP DATABASE IF EXISTS $db WITH (FORCE)"
    psql_admin -c "CREATE DATABASE $db"
  done
  echo "recreated $DEV_DB and $TEST_DB (run db:migrate / db:seed next)"
}

print_urls() {
  echo
  echo "DATABASE_URL=$(url_for "$DEV_DB")"
  echo "TEST_DATABASE_URL=$(url_for "$TEST_DB")"
  if [[ ! -f "$ROOT/.env.local" ]]; then
    {
      echo "# generated by scripts/db-local.sh — local development only"
      echo "DATABASE_URL=$(url_for "$DEV_DB")"
      echo "TEST_DATABASE_URL=$(url_for "$TEST_DB")"
      echo "SITE_URL=http://localhost:3000"
    } >"$ROOT/.env.local"
    echo "(wrote .env.local)"
  elif ! grep -q "127.0.0.1:$(current_port)/" "$ROOT/.env.local"; then
    echo "note: .env.local exists but does not point at this cluster; update DATABASE_URL if needed"
  fi
}

case "${1:-start}" in
  start) cmd_start ;;
  stop) cmd_stop ;;
  status)
    if is_running; then echo "running on port $(current_port)"; print_urls; else echo "not running"; exit 1; fi
    ;;
  reset) cmd_reset ;;
  url)
    if [[ "${2:-}" == "test" ]]; then url_for "$TEST_DB"; else url_for "$DEV_DB"; fi
    ;;
  *)
    echo "usage: $0 {start|stop|status|reset|url [test]}" >&2
    exit 2
    ;;
esac
